//============Student management system====================
const students = [
    { id: 1, name: "Aman", age: 20, marks: 75 },
    { id: 2, name: "Rahul", age: 21, marks: 85 },
    { id: 3, name: "Neha", age: 19, marks: 92 }
];


// Show Students

function showStudents() {

    students.forEach((student) => {
        console.log(
            student.id,
            student.name,
            student.age,
            student.marks
        );
    });

}


// Add Student

function addStudent(id, name, age, marks) {

    const newStudent = {
        id: id,
        name: name,
        age: age,
        marks: marks
    };

    students.push(newStudent);
}


// Update Marks

function updateMarks(id, newMarks) {

    students.forEach((student) => {

        if (student.id === id) {
            student.marks = newMarks;
        }

    });

}


// Delete Student

function deleteStudent(id) {

    const index = students.findIndex((student) => {
        return student.id === id;
    });

    if (index !== -1) {
        students.splice(index, 1);
    }

}


// Check Results

function checkResults() {

    students.forEach((student) => {

        if (student.marks >= 40) {
            console.log(student.name + " : Pass");
        } else {
            console.log(student.name + " : Fail");
        }

    });

}


// Testing

showStudents();

addStudent(4, "Vivek", 22, 80);

updateMarks(2, 95);

deleteStudent(1);

console.log("After Changes:");

showStudents();

console.log("Results:");

checkResults();